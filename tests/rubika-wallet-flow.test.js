const orderId='0fef4f67-3efe-4cee-8675-deadbeefbabe';
const now=Date.now();
const baseOrder={id:orderId,bale_id:-1000000001,status:'pending',total_toman:35000,
 full_name:'کاربر روبیکا',kind:'purchase',days:1,expires_at:new Date(now+1800000).toISOString()};
function fixture(){
 const messages=[],calls=[],rpcs=[],patches=[];
 let bridge={order_id:orderId,virtual_id:-1000000001,state:'claimed',bale_user_id:54321};
 let order={...baseOrder};
 const bale={send:async(id,text,buttons)=>{messages.push({id,text,buttons});return{message_id:7}},
  call:async(method,payload)=>{calls.push({method,payload});
   if(method==='sendInvoice')return{message_id:8};
   if(method==='inquireTransaction')return{id:'transaction1',status:'paid',userID:54321,amount:350000};
   if(method==='answerPreCheckoutQuery')return true;
  }};
 const ctx={platform:'rubika',ready:async()=>true,settings:async()=>({bot_username:'gptyarbot'}),
  secret:async key=>key==='rubika_bot'?'rubika-mock-token-123456':'bale-wallet-token',
  bale:async()=>bale,
  db:{
   rpc:async(name,args)=>{rpcs.push({name,args});
    if(name==='rubika_bridge_issue')return orderId;
    if(name==='rubika_bridge_claim')return order;
    if(name==='rubika_bridge_record')return {...order,status:'paid',paid_at:new Date().toISOString()};
    if(name==='rubika_bridge_precheckout'||name==='precheckout')return true;
    if(name==='rubika_identity')return-1000000001;
    if(name==='rubika_claim_update')return true;
   },
   one:async(table,query)=>table==='rubika_bridges'?bridge:table==='orders'?order:table==='rubika_users'?{rubika_id:'u123456'}:null,
   patch:async(table,query,data)=>{patches.push({table,query,data});return[];}
  },
  lease:async(key,fn)=>fn(),
  transport:async(url,params)=>{
   calls.push({url,params});
   return new Response(JSON.stringify({status:'OK',data:{message_id:'rub-msg'}}),{status:200});
  }
 };
 return {ctx,rpcs,calls,messages,patches,getOrder:()=>order,setOrder:o=>{order=o;}};
}
test('Rubika wallet URL is issued and bound to an actual server-side order, never generated by a browser',async()=>{
 const f=fixture();
 const url=await issueRubikaBaleLink(f.ctx,baseOrder);
 assert.match(url,/^https:\/\/ble\.ir\/gptyarbot\?start=rb_[a-f0-9]{64}$/);
 assert.equal(f.rpcs[0].name,'rubika_bridge_issue');
 assert.equal(f.rpcs[0].args.p_virtual,-1000000001);
 assert.equal(f.rpcs[0].args.p_hash.length,64);
 assert.notEqual(f.rpcs[0].args.p_hash,url.slice(-64)); // hashed nonce, not bearer token
});
test('Bale bot /start bridge sends a payable invoice only to the verified positive Bale account',async()=>{
 const f=fixture();
 const outcome=await startBaleBridge(f.ctx,{from:{id:54321},chat:{id:54321,type:'private'},text:'/start rb_'+random()});
 assert.equal(outcome,true);
 assert.equal(f.rpcs[0].name,'rubika_bridge_claim');
 assert.ok(f.calls.some(c=>c.method==='sendInvoice'&&c.payload.chat_id===54321&&c.payload.payload===orderId));
 assert.equal(f.messages[0].id,54321);
});
